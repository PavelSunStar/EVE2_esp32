#pragma once

// [ --== BT817/BT818 Host Commands ==-- ]

// -----------------------------------------------------------------------------
// Режимы питания
// -----------------------------------------------------------------------------

#define ACTIVE          0x00
// Переводит EVE в активный режим.
// Используется для выхода из STANDBY, SLEEP или PWRDOWN.
// После включения питания обычно отправляется после CLKEXT.

#define STANDBY         0x41
// Режим ожидания.
// Останавливается системная тактовая частота ядра.
// PLL и внешний генератор продолжают работать.
// Выход из режима: команда ACTIVE.

#define SLEEP           0x42
// Режим сна.
// Останавливаются ядро, PLL и генератор.
// Выход из режима: команда ACTIVE.
// CLKSEL необходимо отправлять именно в режиме SLEEP.

#define PWRDOWN         0x43
// Глубокое отключение питания цифрового ядра 1,2 В.
// Выключаются ядро, PLL и генератор.
// SPI-интерфейс продолжает работать.
// Выход из режима: команда ACTIVE.

#define PWRDOWN_ALT     0x50
// Альтернативный код команды PWRDOWN.
// BT817/BT818 официально допускает оба значения: 0x43 и 0x50.


// -----------------------------------------------------------------------------
// Тактовая частота и сброс
// -----------------------------------------------------------------------------

#define CLKEXT          0x44
// Выбирает внешний кварцевый генератор как источник PLL.
// На большинстве готовых BT817/BT818-модулей используется именно CLKEXT.
// При смене источника тактирования выполняется системный сброс.

#define CLKSEL          0x61
// Настраивает множитель системной частоты.
// Второй байт host-команды содержит множитель и диапазон PLL.
//
// Примеры для кварца 12 МГц:
//   0x00 — стандартные 60 МГц
//   0x02 — 24 МГц
//   0x03 — 36 МГц
//   0x44 — 48 МГц
//   0x45 — 60 МГц
//   0x46 — 72 МГц
//
// Команду следует отправлять только в режиме SLEEP.
// После изменения частоты необходимо обновить REG_FREQUENCY.

#define CLKSEL_ALT      0x62
// Альтернативный официальный код CLKSEL.
// Для нашей библиотеки используем основной код 0x61.

#define RST_PULSE       0x68
// Программный импульс сброса ядра BT817/BT818.
// Почти эквивалентен аппаратному Power-On Reset,
// но настройки, заданные host-командами, сохраняются.


// -----------------------------------------------------------------------------
// Настройка выводов
// -----------------------------------------------------------------------------

#define PINDRIVE        0x70
// Настраивает силу выходного тока выбранной группы контактов.
//
// Второй байт:
//   биты [7:2] — номер контакта или группы;
//   биты [1:0] — сила выходного тока:
//
//   0 — минимальная;
//   1 — средняя;
//   2 — высокая;
//   3 — максимальная.
//
// Например, группа 0x13 — линии SPI MOSI/MISO/IO2/IO3.

#define PIN_PD_STATE    0x71
// Определяет состояние выбранной группы выводов в режиме PWRDOWN.
//
// Второй байт:
//   биты [7:2] — номер контакта или группы;
//   биты [1:0] — состояние:
//
//   0 — плавающее состояние;
//   1 — подтяжка к GND;
//   2 — подтяжка к питанию;
//   3 — зарезервировано.
//
// Настройки сохраняются после выхода из PWRDOWN.
// Сбрасываются только полным Power-On Reset.